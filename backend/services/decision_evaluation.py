"""
Candidate group decision evaluation and WAIT_OR_EXPAND_GROUP superset
resolution (Phase 6D).

Authoritative sources:
  - Per-candidate evaluation: Phase 6A's decision_engine.evaluate_group,
    called UNMODIFIED here -- no cost/savings/MOQ/freshness/allocation
    formula is reimplemented anywhere in this file.
  - WAIT_OR_EXPAND_GROUP refinement: Phase 5E Section 12 (the exact
    superset-search-and-terminate rule); Phase 6A's decision_engine.py
    module docstring, which explicitly defers this refinement to a later
    phase and states the exact formula:

        WAIT_OR_EXPAND_GROUP for G  <=>  G's trigger holds, AND
            exists G' superset of G, G' subseteq pool(G):
                Stage2(G') = BUY_TOGETHER

        If no such G' exists: G's final state is DO_NOT_BUY_TOGETHER,
        not an open-ended "keep waiting."

IMPORTANT BOUNDARY, enforced by this module's own design:
  - No new candidate group is ever created here. Every group this module
    evaluates or searches over was already generated by Phase 6C's
    form_candidate_groups (backend.services.group_formation).
  - Superset search is restricted to candidates sharing the SAME
    source_pool_id (Phase 6C's own pool identifier) -- never across pools.
  - The search is a single pass over an already-finite, already-enumerated
    list -- there is no recursion, no repeated expansion, and therefore no
    possibility of an infinite loop.
"""

from collections import defaultdict
from dataclasses import replace
from typing import Dict, List, Sequence

from backend.models.contracts import CommodityParams, ConfigParams, ProcurementContext
from backend.models.decision_contracts import EvaluatedGroupResult
from backend.models.enums import DecisionState
from backend.models.group_formation_contracts import GroupFormationResult
from backend.services import decision_engine


def evaluate_candidate_groups(
    formation_result: GroupFormationResult,
    commodity: CommodityParams,
    context: ProcurementContext,
    config: ConfigParams,
) -> List[EvaluatedGroupResult]:
    """Evaluate every Phase 6C candidate group via Phase 6A's unmodified
    evaluate_group, then apply the WAIT_OR_EXPAND_GROUP refinement
    (resolve_wait_or_expand). Reuses Phase 6A math exclusively."""
    raw_results: List[EvaluatedGroupResult] = []
    for record in formation_result.candidate_groups:
        decision = decision_engine.evaluate_group(record.candidate, commodity, context, config)
        raw_results.append(EvaluatedGroupResult(
            decision=decision,
            final_decision_state=decision.decision_state,  # provisional; refined below
            commodity_id=record.commodity_id,
            context_date=record.context_date,
            source_pool_id=record.source_pool_id,
            pool_vendor_ids=record.pool_vendor_ids,
            vendor_ids=tuple(sorted(m.vendor_id for m in record.candidate.members)),
        ))
    return resolve_wait_or_expand(raw_results)


def resolve_wait_or_expand(evaluated_results: Sequence[EvaluatedGroupResult]) -> List[EvaluatedGroupResult]:
    """Applies Phase 5E Section 12's exact refinement to every result whose
    BASE decision (decision.decision_state) is WAIT_OR_EXPAND_GROUP.
    Results whose base decision is anything else pass through unchanged.

    For each WAIT_OR_EXPAND_GROUP result G:
      1. Look up every OTHER already-evaluated candidate sharing G's
         source_pool_id (never a different pool -- Phase 6D Part 2 Step 4).
      2. Keep only those that are a STRICT superset of G's vendor set
         (contains every vendor in G, plus at least one more) AND whose
         own base decision is BUY_TOGETHER.
      3. If >=1 such superset exists: G's final_decision_state remains
         WAIT_OR_EXPAND_GROUP (never silently upgraded to BUY_TOGETHER --
         Phase 6D Part 2 Step 8); resolving_superset_group_ids records
         which already-generated superset(s) resolved it.
      4. If none exists: G's final_decision_state becomes
         DO_NOT_BUY_TOGETHER (Phase 5E Section 12's termination rule),
         with an explicit reason.

    Does not mutate any input object -- returns a new list of (possibly)
    new EvaluatedGroupResult instances via dataclasses.replace."""
    by_pool: Dict[str, List[EvaluatedGroupResult]] = defaultdict(list)
    for r in evaluated_results:
        by_pool[r.source_pool_id].append(r)

    refined: List[EvaluatedGroupResult] = []
    for r in evaluated_results:
        if r.decision.decision_state != DecisionState.WAIT_OR_EXPAND_GROUP.value:
            refined.append(r)
            continue

        this_vendors = set(r.vendor_ids)
        resolving_ids = []
        for other in by_pool[r.source_pool_id]:
            other_vendors = set(other.vendor_ids)
            is_strict_superset = this_vendors < other_vendors  # strict: proper superset
            if is_strict_superset and other.decision.decision_state == DecisionState.BUY_TOGETHER.value:
                resolving_ids.append(other.decision.group_id)

        if resolving_ids:
            resolving_ids = tuple(sorted(resolving_ids))
            refined.append(replace(
                r,
                final_decision_state=DecisionState.WAIT_OR_EXPAND_GROUP.value,
                resolving_superset_group_ids=resolving_ids,
                expansion_reason=(
                    f"Current group cannot satisfy the MOQ-related requirement on its own, "
                    f"but larger candidate group(s) within the same compatibility pool "
                    f"({r.source_pool_id}) were checked and found feasible: "
                    f"{', '.join(resolving_ids)}. This group's own status remains "
                    f"WAIT_OR_EXPAND_GROUP -- it is not itself eligible for final "
                    f"selection; the resolving superset(s) are evaluated and eligible "
                    f"independently."
                ),
            ))
        else:
            refined.append(replace(
                r,
                final_decision_state=DecisionState.DO_NOT_BUY_TOGETHER.value,
                resolving_superset_group_ids=(),
                expansion_reason=(
                    f"Current group cannot satisfy the MOQ-related requirement on its own, "
                    f"and no already-generated larger group within the same compatibility "
                    f"pool ({r.source_pool_id}) could resolve it (Phase 5E Section 12 "
                    f"termination behavior). Falling back to DO_NOT_BUY_TOGETHER rather "
                    f"than an unresolved, open-ended wait."
                ),
            ))
    return refined
